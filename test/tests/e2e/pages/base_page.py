from playwright.sync_api import Page, expect
import re


class BasePage:
    def __init__(self, page: Page):
        self.page = page

    def navigate(self, url: str):
        self.page.goto(url)

    def get_title(self) -> str:
        return self.page.title()

    def expect_title_contains(self, substring: str):
        expect(self.page).to_have_title(re.compile(substring))

    def check_visual(self, snapshot_name: str):
        expect(self.page).to_have_screenshot(f"{snapshot_name}.png")
