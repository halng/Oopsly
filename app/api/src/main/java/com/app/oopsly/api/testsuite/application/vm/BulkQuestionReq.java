import java.util.List;

/** Questions to add to a test suite in one all-or-nothing call. */
public record BulkQuestionReq(
        @NotEmpty @Size(max = BulkQuestionReq.MAX_QUESTIONS) List<@NotNull @Valid QuestionReq> questions) {

    public static final int MAX_QUESTIONS = 200;
}
